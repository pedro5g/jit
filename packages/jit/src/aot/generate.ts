/** One declaration the generator could not build, and why. */
export interface SkippedOperation {
  readonly schema: string;
  readonly operation: string;
  readonly reason: string;
}

/** `"ts"` emits one typed module; `"js"` emits ready-to-run ESM. */
export type AotOutputFormat = "ts" | "js";

/** First line of every generated module; also the ownership marker for `clean`. */
const GENERATED_BANNER = "// Generated by jit — do not edit.";
const CALL_HELPER =
  "type __JitCall<TFunction> = TFunction extends (...args: infer A) => infer R ? (...args: A) => R : never;";

/** Describes the JIT generate options contract used by the public API. */
export interface GenerateOptions {
  /** Declaration name -> compiled artifact, emitted as one exported function. */
  readonly artifacts?: Readonly<Record<string, unknown>>;
  /** Declaration name -> object of artifacts, emitted as one frozen object. */
  readonly groups?: Readonly<Record<string, Readonly<Record<string, unknown>>>>;
  /** Explicit generated type name -> schema. */
  readonly schemas?: Readonly<Record<string, SchemaInput>>;
  /** Output directory. Previous JIT output there is always replaced. */
  readonly outDir: string;
  /**
   * Source format. `ts` keeps public signatures in the executable source
   * itself and leaves type resolution to the application's own build; `js`
   * emits ready-to-run ESM. The low-level API defaults to `js` while
   * CLI/config default to `ts`.
   */
  readonly format?: AotOutputFormat;
  /**
   * Emit one module per declaration file, named after it, plus an `index`
   * barrel. Requires `sources`; defaults to a single `index` module.
   */
  readonly perFile?: boolean;
  /**
   * Declaration name -> file it was declared in. Drives per-file module
   * names and the precise types of artifacts whose signature can only be
   * read back from the declaration itself.
   */
  readonly sources?: ReadonlyMap<string, string>;
  /** Declaration names the source file exports; those get precise types. */
  readonly exported?: ReadonlySet<string>;
}

/** Describes the JIT generate result contract used by the public API. */
export interface GenerateResult {
  readonly files: readonly string[];
  readonly skipped: readonly SkippedOperation[];
}

interface ModulePlan {
  readonly name: string;
  readonly artifacts: Readonly<Record<string, unknown>>;
  readonly groups: Readonly<Record<string, Readonly<Record<string, unknown>>>>;
  readonly schemas: Readonly<Record<string, SchemaInput>>;
}

interface EmittedModule {
  readonly name: string;
  readonly source: string;
  readonly exports: readonly string[];
  readonly types: readonly string[];
  readonly skipped: readonly SkippedOperation[];
}

interface OutputLayout {
  readonly format: AotOutputFormat;
  readonly extension: ".js" | ".ts";
}

/** A group member or standalone export, already lowered to a binding. */

/**
 * Prisma-style AOT generation: turns declarations into one optimized `.js`
 * or directly typed `.ts` module written to a directory the app imports. The
 * generated module is fully self-contained — the few tiny runtime helpers a
 * strategy may need (validation error class, keyed-index cache) are inlined
 * into the file, so it has zero imports: no engine weight, no module graph
 * to load on cold start, CSP-safe.
 *
 * A declaration file exposes an explicit manifest. `export type User =
 * JIT.Typeof<typeof userSchema>` names a generated type; `export const isUser
 * = JIT.validate.is(userSchema)` becomes `isUser`; and an exported object of
 * artifacts becomes one frozen object with exactly those members.
 */
export function generate(options: GenerateOptions): GenerateResult {
  const layout = resolveOutputLayout(assertOutputFormat(options.format ?? "js"));
  const skipped: SkippedOperation[] = [];
  const modules: EmittedModule[] = [];

  for (const plan of planModules(options)) {
    const emitted = emitModule(plan, options, layout);

    skipped.push(...emitted.skipped);
    if (emitted.exports.length > 0 || emitted.types.length > 0) modules.push(emitted);
  }

  if (modules.length === 0) return { files: [], skipped };

  cleanGeneratedFiles(options.outDir);
  mkdirSync(options.outDir, { recursive: true });

  const files = modules.map((module) => writeFile(options.outDir, `${module.name}${layout.extension}`, module.source));

  if (options.perFile === true) {
    files.push(writeFile(options.outDir, `index${layout.extension}`, emitBarrel(modules, layout)));
  }

  return { files, skipped };
}

/** One module per declaration file, or a single `index` holding everything. */
function planModules(options: GenerateOptions): readonly ModulePlan[] {
  const artifacts = options.artifacts ?? {};
  const groups = options.groups ?? {};
  const schemas = options.schemas ?? {};
  const sources = options.sources;

  if (options.perFile !== true || !sources) return [{ name: "index", artifacts, groups, schemas }];

  const names = [...Object.keys(artifacts), ...Object.keys(groups), ...Object.keys(schemas)];
  const byFile = new Map<string, string[]>();

  for (const name of names) {
    const file = sources.get(name);

    if (!file) continue;
    const bucket = byFile.get(file);

    if (bucket) bucket.push(name);
    else byFile.set(file, [name]);
  }

  const used = new Set<string>();

  return [...byFile].map(([file, declared]) => {
    const selected = new Set(declared);

    return {
      name: uniqueModuleName(moduleNameFromSource(file), used),
      artifacts: pick(artifacts, selected),
      groups: pick(groups, selected),
      schemas: pick(schemas, selected),
    };
  });
}

function pick<TValue>(record: Readonly<Record<string, TValue>>, selected: ReadonlySet<string>): Record<string, TValue> {
  return Object.fromEntries(Object.entries(record).filter(([name]) => selected.has(name)));
}

function emitBarrel(modules: readonly EmittedModule[], layout: OutputLayout): string {
  const lines = [GENERATED_BANNER];

  for (const module of modules) {
    if (layout.format === "ts" && module.types.length > 0) {
      lines.push(`export type { ${module.types.join(", ")} } from "./${module.name}.js";`);
    }
    if (module.exports.length > 0) {
      lines.push(`export { ${module.exports.join(", ")} } from "./${module.name}.js";`);
    }
  }

  return `${lines.join("\n")}\n`;
}

function emitModule(plan: ModulePlan, options: GenerateOptions, layout: OutputLayout): EmittedModule {
  const ts = layout.format === "ts";
  const skipped: SkippedOperation[] = [];
  const js: string[] = [];
  const tsTypes: string[] = [];
  const exportNames: string[] = [];
  const typeNames = new Map<ATS.AnyTypeSchema, string>();
  // A construct stage may refer to a Runtime Class emitted by this module.
  // Keep the source-level binding instead of serializing the runtime
  // constructor as an external closure value.
  const classBindings = new Map<unknown, string>();
  const classArtifacts = new Map<unknown, Extract<CompiledArtifact, { readonly kind: "class" }>>();
  const assertionBindings = new Map<unknown, string>();
  const assertionSources: string[] = [];
  const publicNames = new Set([...Object.keys(plan.artifacts), ...Object.keys(plan.groups)]);
  const internalNames = new Set<string>();
  const exported = options.exported ?? new Set<string>();
  let needsRuntimeGetIndex = false;
  let needsRuntimeCachedIndex = false;
  let needsValidationError = false;
  let needsAssertionError = false;
  let needsHashHelpers = false;
  let needsHashCache = false;
  let needsJsonPatchHelpers = false;
  let needsMockHelpers = false;
  let needsCallHelper = false;
  let needsAggregateType = false;
  let needsDomainStateType = false;
  let needsDomainEventType = false;

  for (const [name, value] of Object.entries(plan.artifacts)) {
    const artifact = getArtifact(value);

    if (isValidIdentifier(name) && artifact?.kind === "class") {
      classBindings.set(value, name);
      classArtifacts.set(value, artifact);
    }
  }

  // Runtime Type schemas carry a compiled assertion guard so the runtime
  // validator can fuse child invariants into the parent's issue buffer. AOT
  // can reconstruct that guard from the declaration-time assertion IR; keep
  // the generated function at module scope so nested validators bind it like
  // any other emitted class artifact.
  for (const [value, artifact] of classArtifacts) {
    const assertion = artifact.policy?.assertions;
    const schema = (value as { readonly schema?: ATS.AnyTypeSchema }).schema;
    if (assertion === undefined || schema?.type !== TypeName.runtimeType) continue;
    const runtimeSchema = schema as ATS.RuntimeTypeSchema;
    if (runtimeSchema.def.assertion === undefined) continue;
    const helper = internalIdentifier(`${classBindings.get(value) ?? "runtime"}_assertion`);
    const lines = [`const ${helper} = /*#__PURE__*/ (() => {`];
    const bindingLines = inlineBindings(assertion.bindingNames, assertion.bindingValues);
    if (bindingLines === undefined) {
      skipped.push({
        schema: classBindings.get(value) ?? "runtime class",
        operation: "class.assert",
        reason: "an assertion value cannot be serialized ahead of time",
      });
      continue;
    }
    lines.push(...bindingLines.map((line) => `  ${line}`));
    for (const [index, failure] of assertion.failures.entries()) {
      lines.push(
        `  const __issue${index} = Object.freeze(${JSON.stringify({
          path: failure.field === undefined ? [] : [failure.field],
          code: failure.code,
          expected: failure.rule ?? "a domain invariant",
          message: failure.message,
        })});`,
        `  const __fail${index} = () => undefined;`
      );
    }
    lines.push(...indentBlock(assertion.source).map((line) => `  ${line}`), "  return __assert;", "})();");
    assertionSources.push(...lines);
    assertionBindings.set(runtimeSchema.def.assertion, helper);
  }

  // Every explicitly requested type is named first, so a schema nested inside another
  // is emitted as its own name instead of being inlined a second time.
  // A generated type and a generated value may share a name: TypeScript keeps
  // them in separate declaration spaces, so `User.is(value)` and `User` as a
  // type both read naturally from the same declaration file.
  for (const name of Object.keys(plan.schemas)) {
    if (!isValidIdentifier(name)) continue;
    const schema = unwrapSchema(plan.schemas[name] as SchemaInput<ATS.AnyTypeSchema>);

    if (!typeNames.has(schema)) typeNames.set(schema, name);
  }

  const typeExports = Object.entries(plan.schemas).flatMap(([name, input]) => {
    if (!isValidIdentifier(name)) return [];
    const schema = unwrapSchema(input as SchemaInput<ATS.AnyTypeSchema>);

    tsTypes.push(`export type ${name} = ${emitTypeScriptType(schema, typeNames)};`);
    return [name];
  });

  js.push(GENERATED_BANNER);
  if (ts) js.push("// @ts-nocheck -- generated internals are typed at the public export boundary.");
  js.push(...assertionSources);
  if (assertionSources.length > 0) js.push("");

  const mark = (flag: ArtifactEmitterFlag): void => {
    if (flag === "runtimeGetIndex") needsRuntimeGetIndex = true;
    else if (flag === "runtimeCachedIndex") needsRuntimeCachedIndex = true;
    else if (flag === "hashHelpers") needsHashHelpers = true;
    else if (flag === "hashCache") needsHashCache = true;
    else if (flag === "jsonPatchHelpers") needsJsonPatchHelpers = true;
    else if (flag === "validationError") needsValidationError = true;
    else if (flag === "assertionError") needsAssertionError = true;
    else if (flag === "aggregateType") needsAggregateType = true;
    else if (flag === "domainStateType") needsDomainStateType = true;
    else if (flag === "domainEventType") needsDomainEventType = true;
    else if (flag === "mockHelpers") needsMockHelpers = true;
    else if (flag === "callHelper") needsCallHelper = true;
  };

  const classArtifactContext: Omit<ClassArtifactEmitContext, "emitValidatorBinding" | "emitHashBinding"> = {
    js,
    skipped,
    mark,
    internalIdentifier,
    classMemberName,
    inlineBindings,
    serializeBindingValue,
    indentBlock,
    asExpression,
    tryEmit,
    classBindings,
    assertionBindings,
    hasNestedValidation,
  };

  const artifactTypeContext: ArtifactTypeContext = {
    typeNames,
    classMemberName,
    classUpdateType,
    mark,
  };

  const emitArtifact = createArtifactEmitter({
    js,
    skipped,
    ts,
    artifactTypeContext,
    classArtifactContext,
    classBindings,
    classArtifacts,
    assertionBindings,
    mark,
    internalIdentifier,
    inlineBindings,
    inlineCodecBindings,
    serializeBindingValue,
    serializeStaticData,
    asExpression,
    indentBlock,
    tryEmit,
  });

  for (const [name, members] of Object.entries(plan.groups)) {
    if (!isValidIdentifier(name)) {
      skipped.push({
        schema: name,
        operation: "group",
        reason: "declaration names must be valid JavaScript identifiers",
      });
      continue;
    }

    const sourceFile = options.sources?.get(name);
    const operations: (EmittedBinding & { readonly prop: string })[] = [];

    for (const prop of Object.keys(members)) {
      const artifact = getArtifact(members[prop]);

      if (!artifact) {
        skipped.push({
          schema: name,
          operation: prop,
          reason: "member is not a compiled JIT artifact",
        });
        continue;
      }

      const memberType =
        exported.has(name) && sourceFile
          ? memberImportType(options.outDir, sourceFile, name, prop, artifact)
          : undefined;
      const emitted = emitArtifact(
        internalIdentifier(`${name}_${prop}`),
        artifact,
        `${name}.${prop}`,
        memberType,
        false
      );

      if (emitted) operations.push({ prop, ...emitted });
    }

    if (operations.length === 0) {
      skipped.push({
        schema: name,
        operation: "group",
        reason: "no member of this object could be generated",
      });
      continue;
    }

    if (ts) {
      js.push(`const ${name}: {`);
      js.push(...operations.map((operation) => `  readonly ${operation.prop}: ${operation.type};`));
      js.push("} = /*#__PURE__*/ Object.freeze({");
    } else {
      js.push(`const ${name} = /*#__PURE__*/ Object.freeze({`);
    }
    js.push(...operations.map((operation) => `  ${operation.prop}: ${operation.binding},`));
    js.push("});");
    js.push("");
    exportNames.push(name);
  }

  for (const [name, value] of Object.entries(plan.artifacts)) {
    if (!isValidIdentifier(name)) {
      skipped.push({
        schema: name,
        operation: "export",
        reason: "declaration names must be valid JavaScript identifiers",
      });
      continue;
    }

    const artifact = getArtifact(value);

    if (!artifact) {
      skipped.push({
        schema: name,
        operation: "export",
        reason: "declaration is not a compiled JIT artifact",
      });
      continue;
    }

    const sourceFile = options.sources?.get(name);
    const declaredType =
      exported.has(name) && sourceFile ? declarationImportType(options.outDir, sourceFile, name, artifact) : undefined;

    if (emitArtifact(name, artifact, name, declaredType, ts)) exportNames.push(name);
  }

  function internalIdentifier(preferred: string): string {
    let candidate = preferred;
    let suffix = 1;

    while (publicNames.has(candidate) || internalNames.has(candidate)) candidate = `${preferred}_${suffix++}`;

    internalNames.add(candidate);
    return candidate;
  }

  function classMemberName(name: string): string {
    return isValidIdentifier(name) ? name : `[${JSON.stringify(name)}]`;
  }

  function classUpdateType(schema: ATS.AnyTypeSchema, seen = new Set<ATS.AnyTypeSchema>()): string {
    if (seen.has(schema)) return emitTypeScriptType(schema, typeNames);
    const resolved = resolveWrappers(schema);
    const base = resolved.base;

    if (base.type === TypeName.object) {
      seen.add(schema);
      const fields = Object.entries((base as ATS.ObjectSchema).def.props)
        .filter(([, child]) => !resolveWrappers(child).readonly)
        .map(([key, child]) => `${JSON.stringify(key)}?: ${classUpdateType(child, seen)}`);
      seen.delete(schema);
      return fields.length === 0 ? "{}" : `{ ${fields.join("; ")} }`;
    }
    if (base.type === TypeName.array) {
      const element = (base as ATS.ArraySchema).def.element;
      return `(${classUpdateType(element, seen)} | undefined)[]`;
    }
    return emitTypeScriptType(schema, typeNames);
  }

  // Inlined runtime helpers keep the module import-free: nothing from the
  // engine is loaded in production, and cold start pays only this file.
  const helpers: string[] = [];

  if (needsAssertionError) {
    helpers.push(
      "class DomainAssertionError extends Error {",
      "  constructor(message, details) {",
      "    super(message);",
      '    this.name = "DomainAssertionError";',
      '    this.code = "ASSERTION_FAILED";',
      "    this.rule = details?.rule;",
      "    this.field = details?.field;",
      "    this.issues = details?.issues ?? [];",
      "    this.path = details?.field === undefined ? undefined : [details.field];",
      "  }",
      "}"
    );
  }
  if (needsValidationError) {
    helpers.push(
      "class JITValidationError extends Error {",
      "  constructor(issues) {",
      "    const first = issues[0];",
      '    const path = first ? first.path.map((segment, index) => typeof segment === "number" ? "[" + segment + "]" : (index === 0 ? "" : ".") + String(segment)).join("") : "";',
      '    super(first ? (path === "" ? "" : path + ": ") + first.message : "validation failed");',
      '    this.name = "JITValidationError";',
      '    this.code = "VALIDATION_FAILED";',
      "    this.issues = issues;",
      "  }",
      "}"
    );
  }
  if (needsHashHelpers) {
    helpers.push(
      "function __hashNumber(value) { return value | 0; }",
      "function __hashBoolean(value) { return value ? 1 : 0; }",
      "function __hashBigInt(value) { return Number(value & 0xffffffffn) | 0; }",
      "function __hashString(value) {",
      "  let hash = 0;",
      "  for (let i = 0, len = value.length; i < len; i++) {",
      "    hash = (hash * 31 + value.charCodeAt(i)) | 0;",
      "  }",
      "  return hash;",
      "}",
      "function __hashUnknown(value) {",
      "  switch (typeof value) {",
      '    case "string": return __hashString(value);',
      '    case "number": return __hashNumber(value);',
      '    case "boolean": return __hashBoolean(value);',
      '    case "bigint": return __hashBigInt(value);',
      '    case "undefined": return 0;',
      '    case "symbol": return __hashString(String(value));',
      '    case "object": return value === null ? 1 : __hashString(Object.prototype.toString.call(value));',
      '    case "function": return __hashString("function");',
      "  }",
      "}",
      "function __combineHash(left, right) { return ((left << 5) - left + right) | 0; }"
    );
    if (needsHashCache) helpers.unshift("const __hashCache = new WeakMap();");
  }
  if (needsJsonPatchHelpers) helpers.push(...JSON_PATCH_HELPERS.split("\n"), ...PATCH_EQUAL_HELPER.split("\n"));
  if (needsMockHelpers) helpers.push(...MOCK_HELPERS.split("\n"));
  if (needsRuntimeGetIndex) {
    helpers.push(
      "const __indexCache = new WeakMap();",
      "function __getIndex(items, key) {",
      "  const cached = __indexCache.get(items);",
      "  if (cached !== undefined && cached.key === key) return cached.map;",
      "  const map = new Map();",
      "  for (let i = 0, len = items.length; i < len; i++) map.set(items[i][key], items[i]);",
      "  __indexCache.set(items, { key: key, map: map });",
      "  return map;",
      "}"
    );
  }
  if (needsRuntimeCachedIndex) {
    helpers.push(
      "const __planCache = new WeakMap();",
      "function __cachedIndex(items, cacheKey, build) {",
      "  let plans = __planCache.get(items);",
      "  if (plans === undefined) { plans = new Map(); __planCache.set(items, plans); }",
      "  const cached = plans.get(cacheKey);",
      "  if (cached !== undefined) return cached;",
      "  const built = build(items);",
      "  plans.set(cacheKey, built);",
      "  return built;",
      "}"
    );
  }

  const preludeIndex = ts ? 2 : 1;

  if (helpers.length > 0) js.splice(preludeIndex, 0, ...helpers);
  if (ts && tsTypes.length > 0) js.splice(preludeIndex, 0, ...tsTypes, "");
  if (ts && needsDomainStateType) {
    js.splice(preludeIndex, 0, "declare class __JitDomainState<TProps> {", "  protected readonly _props: TProps;", "}");
  }
  if (ts && needsDomainEventType) {
    js.splice(
      preludeIndex,
      0,
      "declare const __JitDomainEvent: unique symbol;",
      "interface __JitDomainEventBrand { readonly [__JitDomainEvent]: true; }"
    );
  }
  if (ts && needsAggregateType) {
    js.splice(
      preludeIndex,
      0,
      "declare class __JitAggregate<TPatch, TEvent extends __JitDomainEventBrand> {",
      "  protected raise(event: TEvent): void;",
      "  peekEvents(): readonly TEvent[];",
      "  pullEvents(): TEvent[];",
      "  commit(publisher: { publish(event: TEvent): void | PromiseLike<void> }): Promise<void>;",
      "}"
    );
  }
  if (ts && needsCallHelper) js.splice(preludeIndex, 0, CALL_HELPER);

  const source =
    exportNames.length > 0
      ? `${js.join("\n")}\nexport { ${exportNames.join(", ")} };\n`
      : `${js.join("\n")}\nexport {};\n`;

  return {
    name: plan.name,
    source,
    exports: exportNames,
    types: ts ? typeExports : [],
    skipped,
  };
}

/**
 * Artifacts built from a developer callback chain (queries, mappers,
 * watchers) have no runtime metadata precise enough to rebuild their
 * signature, so the generated module reads it back from the declaration
 * that produced it. That reference is type-only and disappears at build.
 */
function moduleNameFromSource(sourceFile: string): string {
  const rawName = basename(sourceFile)
    .replace(/\.jit\.(ts|mts|cts|js|mjs|cjs)$/, "")
    .replace(/\.(ts|mts|cts|js|mjs|cjs)$/, "");
  const normalized = rawName.replace(/[^A-Za-z0-9_-]/g, "-").replace(/^-+|-+$/g, "");

  return normalized.length > 0 ? normalized : "schema";
}

function uniqueModuleName(preferred: string, used: Set<string>): string {
  let candidate = preferred;
  let suffix = 1;

  while (used.has(candidate) || candidate === "index") candidate = `${preferred}-${++suffix}`;
  used.add(candidate);
  return candidate;
}

function tryEmit<TValue>(
  schema: string,
  operation: string,
  skipped: SkippedOperation[],
  emit: () => TValue
): TValue | undefined {
  try {
    return emit();
  } catch (error) {
    skipped.push({
      schema,
      operation,
      reason: error instanceof Error ? error.message : String(error),
    });
    return undefined;
  }
}

/**
 * Serializes compiler bindings into const declarations. Developer callbacks
 * are emitted as source so generated modules stay self-contained and do not
 * pay a runtime compiler cost.
 */
function inlineBindings(names: readonly string[], values: readonly unknown[]): string[] | undefined {
  const lines: string[] = [];

  for (let index = 0; index < names.length; index++) {
    const value = values[index];
    const literal = serializeBindingValue(value);

    if (literal === undefined) return undefined;

    lines.push(`const ${names[index]} = ${literal};`);
  }

  return lines;
}

function inlineCodecBindings(names: readonly string[], values: readonly unknown[]): string[] | undefined {
  const lines: string[] = [];

  for (let index = 0; index < names.length; index++) {
    const name = names[index];
    const value = values[index];

    if (name === "__enc") {
      lines.push("const __enc = new TextEncoder();");
      continue;
    }

    if (name === "__dec") {
      lines.push("const __dec = new TextDecoder();");
      continue;
    }

    const literal = serializeBindingValue(value);

    if (literal === undefined) return undefined;

    lines.push(`const ${name} = ${literal};`);
  }

  return lines;
}

function serializeBindingValue(value: unknown): string | undefined {
  if (value instanceof RegExp) return String(value);
  if (typeof value === "function") return serializeCallback(value);
  if (value === null || typeof value === "string" || typeof value === "number" || typeof value === "boolean") {
    return JSON.stringify(value);
  }
  if (value === undefined) return "undefined";
  if (Array.isArray(value)) {
    const parts = value.map(serializeBindingValue);

    if (parts.some((part) => part === undefined)) return undefined;
    return `[${parts.join(", ")}]`;
  }

  return undefined;
}

/** Whether an unvalidated materializer still has an explicitly validated child. */
function hasNestedValidation(schema: ATS.AnyTypeSchema, seen = new Set<ATS.AnyTypeSchema>()): boolean {
  const current = resolveLazySchema(schema);
  if (seen.has(current)) return false;
  seen.add(current);

  if (current.type === TypeName.runtimeType) {
    const runtime = current as ATS.RuntimeTypeSchema;
    if (runtime.def.traits.factoryPolicy.validationConfigured === true || runtime.def.assertion !== undefined)
      return true;
  }

  return schemaChildren(current).some((child) => hasNestedValidation(child, seen));
}

/** Serializes data-only update patches without evaluating getters or prototypes. */
function serializeStaticData(value: unknown, seen = new Set<object>()): string | undefined {
  if (value === null) return "null";

  switch (typeof value) {
    case "string":
      return JSON.stringify(value);
    case "boolean":
      return value ? "true" : "false";
    case "undefined":
      return "undefined";
    case "bigint":
      return `${value}n`;
    case "number":
      if (Number.isNaN(value)) return "NaN";
      if (value === Infinity) return "Infinity";
      if (value === -Infinity) return "-Infinity";
      if (Object.is(value, -0)) return "-0";
      return String(value);
    case "object":
      break;
    default:
      return undefined;
  }

  if (seen.has(value)) return undefined;
  seen.add(value);

  try {
    if (value instanceof Date) {
      const time = value.getTime();
      return Number.isNaN(time) ? "new Date(NaN)" : `new Date(${time})`;
    }

    if (Array.isArray(value)) {
      const items = value.map((item) => serializeStaticData(item, seen));

      if (items.some((item) => item === undefined)) return undefined;
      return `[${items.join(", ")}]`;
    }

    const prototype = Object.getPrototypeOf(value);
    if (prototype !== Object.prototype && prototype !== null) return undefined;
    const descriptors = Object.getOwnPropertyDescriptors(value);
    const entries: string[] = [];

    for (const key of Object.keys(descriptors)) {
      const descriptor = descriptors[key];
      if (descriptor === undefined || !("value" in descriptor)) return undefined;
      const entry = serializeStaticData(descriptor.value, seen);
      if (entry === undefined) return undefined;
      entries.push(`${JSON.stringify(key)}: ${entry}`);
    }
    return `{ ${entries.join(", ")} }`;
  } finally {
    seen.delete(value);
  }
}

/**
 * Wraps an emitted source so it reads as a single expression.
 *
 * A schema with a cycle emits one named helper per participant alongside its
 * entry point, so the source is a sequence of declarations rather than one
 * function expression. Those are evaluated once and the entry point returned
 * by name — order-independent, and the same shape the runtime `Function` body
 * already has. An acyclic source is a lone function expression and is
 * parenthesized exactly as before.
 */
function asExpression(source: string, entry: string): string {
  const trimmed = source.trimStart();

  // Already a self-contained expression — a serializer wraps its own IIFE.
  if (!trimmed.startsWith("function ")) return `(${source})`;

  // Bodies are indented, so a top-level match counts declarations. One means
  // the historical single-function shape, which is parenthesized unchanged.
  const declarations = trimmed.match(/^function /gm)?.length ?? 0;

  if (declarations <= 1) return `(${source})`;

  return `/*#__PURE__*/ (() => {\n${source}\nreturn ${entry};\n})()`;
}

function resolveOutputLayout(format: AotOutputFormat): OutputLayout {
  return { format, extension: format === "ts" ? ".ts" : ".js" };
}

function assertOutputFormat(value: unknown): AotOutputFormat {
  if (value === "ts" || value === "js") return value;
  throw new Error(`unknown AOT output format ${JSON.stringify(value)}; expected "ts" or "js"`);
}

function indentBlock(source: string): string[] {
  return source.split("\n").map((line) => (line.length > 0 ? `  ${line}` : line));
}

function writeFile(dir: string, name: string, content: string): string {
  const path = join(/* turbopackIgnore: true */ dir, name);

  writeFileSync(path, content);
  return path;
}

/**
 * Removes JIT-owned output from a previous generation — including modules
 * from a different layout or from declaration files that no longer exist —
 * without ever touching a file JIT did not write. Ownership is decided by
 * the generated banner, not by a name list.
 */
function cleanGeneratedFiles(dir: string): void {
  let entries: readonly string[];

  try {
    entries = readdirSync(/* turbopackIgnore: true */ dir);
  } catch {
    return;
  }

  for (const entry of entries) {
    const path = join(/* turbopackIgnore: true */ dir, entry);

    if (entry === "plans") {
      rmSync(path, { recursive: true, force: true });
      continue;
    }
    if (entry === "manifest.json" || entry === "package.json") {
      if (isGeneratedJson(path)) rmSync(path, { force: true });
      continue;
    }
    if (!/\.(?:m|c)?[jt]s$/.test(entry)) continue;
    if (isGeneratedSource(path)) rmSync(path, { force: true });
  }
}

function isGeneratedSource(path: string): boolean {
  try {
    return readFileSync(path, "utf8").startsWith(GENERATED_BANNER);
  } catch {
    return false;
  }
}

function isGeneratedJson(path: string): boolean {
  // Metadata from earlier JIT layouts; a hand-written manifest is left alone.
  try {
    const parsed = JSON.parse(readFileSync(path, "utf8")) as {
      readonly version?: unknown;
      readonly sideEffects?: unknown;
    };

    return parsed.version === 2 || parsed.version === "0.0.0" || parsed.sideEffects === false;
  } catch {
    return false;
  }
}
